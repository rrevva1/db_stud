"""Generate ALL lesson files for parts 0, 1, 2 (28 lessons × 3 files)."""
import json
import os

LESSONS_DIR = r"e:\Projects\db_stud\course\content\lessons"
CURRICULUM_PATH = r"e:\Projects\db_stud\course\content\curriculum.json"


def build_md(lesson: dict) -> str:
    """Build lesson markdown: title, objectives, theory, sources."""
    lines = [
        f"## {lesson['title']}",
        "",
        f"**Часть:** {lesson['part']} · **Модуль:** {lesson['module']}",
        "",
        "### Цели урока",
        "",
    ]
    for obj in lesson["objectives"]:
        lines.append(f"- {obj}")
    lines.extend(["", lesson["theory"].strip(), "", "### Источники", ""])
    for src_id, ref in lesson["sources"]:
        lines.append(f"- **{src_id}**: {ref}")
    return "\n".join(lines) + "\n"


def write_lesson(lesson: dict) -> int:
    """Write .md, .quiz.json, .tasks.md for one lesson. Returns files written."""
    lid = lesson["id"]
    os.makedirs(LESSONS_DIR, exist_ok=True)

    md_path = os.path.join(LESSONS_DIR, f"{lid}.md")
    with open(md_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(build_md(lesson))

    quiz_path = os.path.join(LESSONS_DIR, f"{lid}.quiz.json")
    quiz_data = {
        "lessonId": lid,
        "passingScore": 70,
        "questions": lesson["quiz"],
    }
    with open(quiz_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(quiz_data, ensure_ascii=False, indent=2) + "\n")

    tasks_path = os.path.join(LESSONS_DIR, f"{lid}.tasks.md")
    with open(tasks_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(lesson["tasks"].strip() + "\n")

    return 3


def load_meta_from_curriculum() -> dict:
    """Load part/module/objectives/sources from curriculum.json keyed by lesson id."""
    with open(CURRICULUM_PATH, encoding="utf-8") as f:
        data = json.load(f)
    meta = {}
    for part in data["parts"][:3]:
        for module in part["modules"]:
            for les in module["lessons"]:
                meta[les["id"]] = {
                    "title": les["title"],
                    "part": part["title"],
                    "module": module["title"],
                    "objectives": les["objectives"],
                    "sources": [
                        (s["sourceId"], s["ref"]) for s in les["requiredSources"]
                    ],
                }
    return meta


